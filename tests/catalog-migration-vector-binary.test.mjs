test('native binary has exact network header/float32 bits, including negative zero and subnormals', () => {
  // Known binary bytes, not bytes generated by the implementation under test.
  const hex = '000700003f800000c020000080000000000000017f7fffffc048f5c33dcccccd';
  const encoded = Buffer.from(hex, 'hex').toString('base64');
  const values = decodePgvectorSendBase64(encoded, 7);
  assert.equal(values[0], 1); assert.equal(values[1], -2.5); assert.ok(Object.is(values[2], -0));
  assert.equal(values[3], 2 ** -149); assert.equal(values[4], Math.fround(3.4028234663852886e38));
  assert.equal(values[5], Math.fround(-3.14)); assert.equal(values[6], Math.fround(0.1));
  assert.notEqual(values[6], 0.1); // No silent promotion of decimal text to original float32.
  assert.equal(Buffer.from(encodePgvectorSendBase64(values), 'base64').toString('hex'), hex);
});

test('binary decode rejects wrong dimensions, little-endian header, trailing/truncated bytes, reserved bits and non-finite values', () => {
  const valid = Buffer.from('000200003f800000c0200000', 'hex');
  const changed = (offset, value) => { const bytes = Buffer.from(valid); bytes[offset] = value; return bytes.toString('base64'); };
  assert.throws(() => decodePgvectorSendBase64(valid.toString('base64')), /dimensions/);
  assert.throws(() => decodePgvectorSendBase64(changed(0, 2), 2), /dimensions/);
  assert.throws(() => decodePgvectorSendBase64(changed(3, 1), 2), /reserved/);
  assert.throws(() => decodePgvectorSendBase64(valid.subarray(0, -1).toString('base64'), 2), /length/);
  assert.throws(() => decodePgvectorSendBase64(Buffer.concat([valid, Buffer.from([0])]).toString('base64'), 2), /length/);
  for (const bits of ['7f800000', 'ff800000', '7fc00001']) {
    const bytes = Buffer.from(`00010000${bits}`, 'hex');
    assert.throws(() => decodePgvectorSendBase64(bytes.toString('base64'), 1), /Non-finite/);
  }
  for (const bad of ['@@@=', 'AB==', 'AAAA\n', '']) assert.throws(() => decodePgvectorSendBase64(bad), /base64/);
  assert.throws(() => encodePgvectorSendBase64([0.1]), /exact finite float32/);
});

test('all 1536 original float32 bit patterns round-trip without regeneration and remain keyed by public UUID', () => {
  const values = Array.from({ length: 1536 }, (_, index) => Math.fround(Math.sin(index) / (index + 1)));
  const base64 = encodePgvectorSendBase64(values);
  assert.equal(Buffer.from(base64, 'base64').length, 4 + 1536 * 4);
  assert.equal(encodePgvectorSendBase64(decodePgvectorSendBase64(base64)), base64);
  const metadata = { catalogRevision: 'test-only', eligible: false, embeddingTextHash: sha256('fixture') };
  const result = exportVector({ public_id: '00000000-0000-4000-8000-000000000001', embedding: base64 }, metadata, PGVECTOR_BINARY_ENCODING);
  assert.deepEqual(result.values, values); assert.deepEqual(result.metadata, metadata);
  assert.equal(result.id, '00000000-0000-4000-8000-000000000001');
  assert.equal(exportVector({ embedding: null }, metadata, PGVECTOR_BINARY_ENCODING), null);
});

test('legacy PG shortest-decimal text and native binary restore identical float32 bytes without fabricating input provenance', () => {
  const decimals = ['0.1', '-0', '1.40129846e-45', '3.4028235e38', '-2.5', ...Array(1531).fill('0.012345679')];
  const text = `[${decimals.join(',')}]`; const values = JSON.parse(text).map(Math.fround);
  const base64 = encodePgvectorSendBase64(values);
  const metadata = { catalogRevision: 'test-legacy', eligible: false };
  const textResult = exportLegacyVector({ public_id: 'test-public-id', embedding: text }, metadata, 'postgres-text');
  const binaryResult = exportLegacyVector({ public_id: 'test-public-id', embedding: base64 }, metadata, PGVECTOR_BINARY_ENCODING);
  assert.deepEqual(textResult, binaryResult);
  assert.ok(Object.is(textResult.values[1], -0));
  assert.equal(textResult.metadata.legacyInputProvenance, 'unverified');
  assert.match(textResult.metadata.vectorBytesSha256, /^[a-f0-9]{64}$/);
  assert.equal('embeddingTextHash' in textResult.metadata, false);
  assert.equal('sourceFactsHash' in textResult.metadata, false);
  assert.equal(exportLegacyVector({ embedding: null }, metadata, 'postgres-text'), null);
  assert.throws(() => exportLegacyVector({ embedding: text }, metadata, 'unknown'), /Unknown/);
  assert.throws(() => exportLegacyVector({ public_id: 'test', embedding: `[1e39,${Array(1535).fill('0').join(',')}]` }, metadata, 'postgres-text'), /finite float32/);
});

const info = { extensionVersion: '0.8.7', typeOid: '4242', typeSchema: 'public', typeName: 'vector',
  functionSchema: 'public', functionName: 'vector_send', returnType: 'bytea', canExecute: true };
const table = { schema: 'public', name: 'products', kind: 'r', partition: false,
  columns: [{ name: 'id', type: 'text', typeOid: '25', nullable: false, default: null },
    { name: 'embedding', type: 'vector(1536)', typeOid: '4242', nullable: true, default: null },
    { name: 'other_vector', type: 'vector(1536)', typeOid: '4242', nullable: true, default: null },
    { name: 'price', type: 'numeric(10,2)', typeOid: '1700', nullable: true, default: null },
    { name: 'created_at', type: 'timestamp without time zone', typeOid: '1114', nullable: true, default: null }],
  constraints: [], indexes: [] };
function source({ metadata = info, probe = '000200003f800000c0200000', malformedVector = false } = {}) {
  const base64 = encodePgvectorSendBase64(Array(1536).fill(Math.fround(0.0123456789)));
  const row = { id: 'TEST-ONLY', embedding: malformedVector ? encodePgvectorSendBase64([1]) : base64,
    other_vector: '[1,2,3]', price: '12.34', created_at: '2026-10-19 15:31:58.50259' };
  const rows = [{ row: JSON.stringify(row) }];
  const stats = [{ row_count: '1', wire_bytes: String(Buffer.byteLength(JSON.stringify(rows[0].row)) + 32) }];
  const queriesSeen = [];
  return { queriesSeen, row,
    async query(sql) {
      queriesSeen.push(sql);
      if (sql.includes('AS vector_send')) return [{ vector_send: JSON.stringify(metadata) }];
      if (sql.includes('AS probe')) return [{ probe }];
      return [{ inventory: JSON.stringify([table]) }];
    },
    async transaction(queries) {
      queriesSeen.push(...queries);
      if (queries.length === 1) return [stats];
      return [[{ settings: '{"isolation":"repeatable read","readOnly":"on","snapshot":"1:2:"}' }],
        [{ inventory: JSON.stringify([table]) }], [{ sequences: '[]' }], stats, rows, [{ inventory: JSON.stringify([table]) }]];
    } };
}

test('binary mode verifies native function/protocol, specializes only embedding, and records explicit manifest column encoding', async () => {
  const input = source(); const exported = await collectConsistentExport(input, { embeddingEncoding: 'pgvector-send-base64' });
  assert.deepEqual(JSON.parse(exported.tables[0].data), input.row);
  assert.ok(input.queriesSeen.some((sql) => sql.includes('"public"."vector_send"("embedding")')));
  assert.ok(input.queriesSeen.some((sql) => sql.includes('"other_vector"::text')));
  assert.ok(input.queriesSeen.some((sql) => sql.includes('"price"::text')));
  assert.equal(exported.vectorSend.extensionVersion, info.extensionVersion);
  const parent = await mkdtemp(join(tmpdir(), 'stupid-gifts-binary-test-'));
  try {
    const output = join(parent, 'protected');
    await writeProtectedExport(exported, { output, repository: process.cwd(), codeSha: 'test-only' });
    const manifest = JSON.parse(await readFile(join(output, 'manifest.json'), 'utf8'));
    assert.equal(manifest.valueEncoding, 'column-specific-v1');
    assert.equal(manifest.tables[0].columnEncodings.embedding, PGVECTOR_BINARY_ENCODING);
    assert.equal(manifest.tables[0].columnEncodings.other_vector, 'postgres-text');
    assert.equal(manifest.tables[0].columnEncodings.created_at, 'postgres-text');
    assert.equal(manifest.tables[0].columnEncodings.price, 'postgres-text');
  } finally { await rm(parent, { recursive: true, force: true }); }
});

test('unsupported native function, unexpected protocol and malformed native values refuse before a completed artifact', async () => {
  await assert.rejects(verifyVectorSend(source({ metadata: { ...info, canExecute: false } })), /unavailable or unsupported/);
  await assert.rejects(verifyVectorSend(source({ probe: '020000000000803f000020c0' })), /did not match/);
  await assert.rejects(collectConsistentExport(source({ malformedVector: true }), { embeddingEncoding: 'pgvector-send-base64' }), /dimensions/);
});
